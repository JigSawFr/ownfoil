"""A throwaway Ownfoil with Lantern on, over fictional games, for Lantern's conformance suite.

    python tests/lantern_conformance/server.py <work folder> <https port>

It writes `<work folder>/ready.json` (the key to pin, a token with every scope and the seed of the key it is
bound to) once it listens, and serves until it is stopped. Nothing here is a real game: the files are
generated bytes under invented names.
"""
import base64
import datetime
import hashlib
import json
import os
import sys
import tempfile

work, https_port = sys.argv[1], int(sys.argv[2])
os.environ['OWNFOIL_CONFIG_DIR'] = tempfile.mkdtemp(prefix='ownfoil-conformance-', dir=work)
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'app'))
sys.argv = sys.argv[:1]

import yaml  # noqa: E402

import constants  # noqa: E402
from settings import get_settings  # noqa: E402

get_settings()
with open(constants.CONFIG_FILE) as handle:
    config = yaml.safe_load(handle)
config['lantern'].update(enabled=True, https_port=https_port, dnssd=False,
                         deltas={'enabled': True, 'types': ['update', 'base', 'dlc'], 'min': 1000, 'max': 50_000_000})
config['shop']['public'] = False
with open(constants.CONFIG_FILE, 'w') as handle:
    yaml.safe_dump(config, handle)

from lantern import ed25519  # noqa: E402
from lantern.server.accounts import SCOPES  # noqa: E402

from app import app  # noqa: E402
from db import Apps, Files, Libraries, Titles, User, db  # noqa: E402
from lantern_server import hashing, tls  # noqa: E402
from lantern_server.accounts import OwnfoilAccounts, ensure_account  # noqa: E402

GAMES = (
    ('Lumen Drift', '0100AB1200010000', '0100AB1200010000', 'BASE', '0', '1.0.0', 'nsp'),
    ('Lumen Drift', '0100AB1200010000', '0100AB1200010800', 'UPDATE', '65536', '1.1.0', 'nsz'),
    ('Lumen Drift Comet', '0100AB1200010000', '0100AB1200011001', 'DLC', '0', None, 'nsp'),
    ('Copper Moth', '0100CD3400020000', '0100CD3400020000', 'BASE', '0', '1.0.0', 'xci'),
)


def blob(label, size=300_000):
    out = bytearray()
    n = 0
    while len(out) < size:
        out += hashlib.sha256(f'{label}:{n}'.encode()).digest()
        n += 1
    return bytes(out[:size])


games = os.path.join(work, 'games')
os.makedirs(games, exist_ok=True)
with app.app_context():
    db.create_all()
    library = Libraries(path=games)
    db.session.add(library)
    db.session.commit()
    titles = {}
    for name, title_id, app_id, kind, version, display, extension in GAMES:
        title = titles.get(title_id) or Titles(title_id=title_id)
        titles[title_id] = title
        db.session.add(title)
        db.session.flush()
        path = os.path.join(games, f'{name} [{app_id}][v{version}].{extension}')
        with open(path, 'wb') as out:
            out.write(blob(path))
        file = Files(filepath=path, library_id=library.id, folder=games, filename=os.path.basename(path),
                     extension=extension, size=os.path.getsize(path), mtime=os.path.getmtime(path),
                     added_at=datetime.datetime(2026, 11, 7, 12, 0, 0))
        row = Apps(title_id=title.id, app_id=app_id, app_version=version, app_type=kind, owned=True,
                   display_version=display)
        db.session.add_all([file, row])
        file.apps.append(row)
        db.session.commit()
        assert hashing.hash_file(file)
        db.session.commit()
    admin = User(user='admin', password='x', admin_access=True, shop_access=True, backup_access=True)
    db.session.add(admin)
    db.session.commit()
    seed = hashlib.sha256(b'a fictional conformance key').digest()
    token, _ = OwnfoilAccounts().issue(ensure_account(admin).name, 'conformance', SCOPES, key=ed25519.public_key(seed))

tls.reconcile(app)
with open(os.path.join(work, 'ready.json'), 'w') as handle:
    json.dump({'pin': tls.spki(), 'token': token, 'key': base64.b64encode(seed).decode()}, handle)
app.run('127.0.0.1', 0, threaded=True)
